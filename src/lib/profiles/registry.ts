function indexProfiles(list: ActivityProfile[]): Record<string, ActivityProfile> {
  const out: Record<string, ActivityProfile> = {}
  for (const profile of list) {
    if (out[profile.id]) throw new Error(`[profiles] Duplicate profile id: ${profile.id}`)
    for (const e of profile.extensions) {
      if (!EXTENSIONS[e]) throw new Error(`[profiles] Profile references unknown extension: ${e}`)
    }
    out[profile.id] = profile
  }
  return out
}

export const PROFILES: Record<string, ActivityProfile> = indexProfiles(PROFILE_LIST)

/** Universal fallback: never assume salon-specific behavior (§21). */
export const GENERIC_PROFILE_ID = "generic"

export function getProfile(id: string | null | undefined): ActivityProfile {
  if (id && PROFILES[id]) return PROFILES[id]
  return PROFILES[GENERIC_PROFILE_ID]
}

export function listProfiles(): ActivityProfile[] {
  return PROFILE_LIST
}

/** Client-safe options for pickers (onboarding, admin selectors). */
export function listProfileOptions(): ProfileOption[] {
  return PROFILE_LIST.map((p) => ({
    id: p.id,
    label: p.label,
    description: p.description,
    palette: p.palette,
    ...(p.catalog?.seedVerticalId ? { catalog: { seedVerticalId: p.catalog.seedVerticalId } } : {}),
  }))
}

/**
 * Whether a capability is enabled for the given (effective) profile.
 * Politika "VSI MODULI ZA VSE" (2026): dejavnost sama ne izključi nobenega
 * modula — vhod ni več nikoli "disabled" kar tako po dejavnosti. Klici jo
 * uporabljajo z EFEKTIVNIM profilom (resolveEffectiveProfile /
 * resolvePublicEffectiveProfile), ki že upošteva dejanska module stanja
 * (izklopljen modul → capability "disabled"), zato tukaj surovo preverimo
 * "disabled" — tako javne 404 strani sledijo pravemu (vklop/izklop) stanju.
 */
export function isCapabilityEnabled(profile: ActivityProfile, key: CapabilityKey): boolean {
  return profile.capabilities[key] !== "disabled"
}

/** Terminology lookup for a locale. */
export function term(
  profile: ActivityProfile,
  key: keyof ActivityProfile["terminology"],
  locale: "sl" | "en"
): string {
  const entry = profile.terminology[key]
  return locale === "en" ? entry.en : entry.sl
}

